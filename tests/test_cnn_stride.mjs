import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const uri=source=>'data:text/javascript;base64,'+Buffer.from(source).toString('base64');
const cnnSource=await readFile(new URL('../upstream/cnn-explainer/src/utils/cnn.js',import.meta.url),'utf8');
const cnnUrl=uri(cnnSource);
const {singleConv}=await import(cnnUrl);
const utilsSource=await readFile(new URL('../upstream/cnn-explainer/src/detail-view/DetailviewUtils.js',import.meta.url),'utf8');
const {generateOutputMappings,compute_input_multiplies_with_weight}=await import(uri(utilsSource.replace("'../utils/cnn.js'",JSON.stringify(cnnUrl))));
const input=Array.from({length:5},(_,r)=>Array.from({length:5},(_,c)=>r*5+c));
const kernel=[[1,0],[0,1]];
const output=singleConv(input,kernel,2);
assert.deepEqual(output,[[6,10],[26,30]]);
assert.equal(singleConv(input,kernel,1).length,4);
assert.equal(singleConv(input,kernel,4).length,1);
const mapping=generateOutputMappings(2,output,2,5,1);
assert.deepEqual(mapping[1][1],[[12,13],[17,18]]);
const highlights=compute_input_multiplies_with_weight(1,1,5,2,mapping,2);
assert.deepEqual(highlights.flatMap((x,i)=>x===undefined?[]:[i]),[12,13,17,18]);
console.log('PASS: non-divisible convolution stride and actual highlighted input window');
