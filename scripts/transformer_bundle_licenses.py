#!/usr/bin/env python3
"""Collect Transformer JS dependency notices from an audit build's source maps.

First run `npx vite build --sourcemap` inside upstream/transformer-explainer.
Maps identify top-level sources, not dependencies hidden inside prebundled JS,
WASM, CSS, CDN resources, model data, or build tooling.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from gan_bundle_licenses import license_text

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / 'upstream' / 'transformer-explainer'
BUILD = APP / 'build'
OUTPUT = ROOT / 'third-party-licenses' / 'transformer-js-source-map-notices.txt'
ONNX_LICENSE = ROOT / 'third-party-licenses' / 'onnxruntime.LICENSE'


def package_for(source: str, virtual_map: Path) -> Path | None:
    normalized = source.replace('\\', '/')
    if 'node_modules' not in normalized.split('/'):
        return None
    source_path = (virtual_map.parent / source).resolve()
    if not source_path.is_file():
        raise RuntimeError(f'Cannot resolve source-map entry {source} from {virtual_map}')
    for directory in source_path.parents:
        if directory == APP:
            break
        manifest = directory / 'package.json'
        if 'node_modules' in directory.parts and manifest.is_file():
            metadata = json.loads(manifest.read_text(encoding='utf-8'))
            if metadata.get('name') and metadata.get('version'):
                return directory
    raise RuntimeError(f'Cannot identify package for {source}')


def notice(package: Path, name: str, version: str) -> tuple[str, str]:
    if (name, version) in {('onnxruntime-web', '1.14.0'), ('onnxruntime-web', '1.23.0'), ('onnxruntime-common', '1.14.0')}:
        return 'ONNX Runtime repository LICENSE, identical at v1.14.0 and v1.23.0', ONNX_LICENSE.read_text(encoding='utf-8').strip()
    if (name, version) == ('gsap', '3.13.0'):
        source = (package / 'gsap-core.js').read_text(encoding='utf-8')
        start = source.find('/*!')
        if start < 0 or 'https://gsap.com/standard-license' not in source[start:start + 1000]:
            raise RuntimeError('Unexpected GSAP notice; inspect package and its license')
        return 'gsap-core.js header; full terms at https://gsap.com/standard-license/', source[start:source.index('*/', start) + 2].strip()
    return license_text(package)


def report() -> str:
    maps = sorted((BUILD / '_app' / 'immutable').rglob('*.js.map'))
    js_files = sorted((BUILD / '_app' / 'immutable').rglob('*.js'))
    if not maps or {p.with_suffix('') for p in maps} != set(js_files):
        raise RuntimeError('Missing JS source maps; build with npx vite build --sourcemap')
    packages = {}
    for path in maps:
        data = json.loads(path.read_text(encoding='utf-8'))
        if data.get('version') != 3 or data.get('file') != path.name.removesuffix('.map') or 'sources' not in data:
            raise RuntimeError(f'Unexpected source map: {path}')
        # adapter-static copies maps from this Vite output directory to build/;
        # original relative paths are anchored at the pre-copy directory.
        virtual_map = APP / '.svelte-kit' / 'output' / 'client' / path.relative_to(BUILD)
        for source in data['sources']:
            package = package_for(source, virtual_map)
            if package is None:
                continue
            metadata = json.loads((package / 'package.json').read_text(encoding='utf-8'))
            name, version = metadata['name'], metadata['version']
            declared = metadata.get('license', 'not declared')
            if not isinstance(declared, str):
                declared = json.dumps(declared, ensure_ascii=False, sort_keys=True)
            filename, content = notice(package, name, version)
            packages[(name, version, package.relative_to(APP).as_posix())] = (declared, filename, content)
    if not packages:
        raise RuntimeError('No dependency packages found in Transformer source maps')
    text = ('Transformer Explainer JavaScript source-map dependency notices\n'
            'Generated by scripts/transformer_bundle_licenses.py from the audit build.\n'
            'Package coverage is based on source-map entries, not a full distribution audit.\n'
            'Prebundled library dependencies, WASM, CSS, CDN resources, models and assets require separate review.\n'
            'GSAP has a separate standard license; its complete terms are linked, not copied here.\n')
    for (name, version, path), (declared, filename, content) in sorted(packages.items()):
        text += f'\n{"=" * 72}\n{name} {version}\nDeclared license: {declared}\nInstalled path: {path}\nNotice source: {filename}\n\n{content}\n'
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        content = report()
        if args.check:
            if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != content:
                raise RuntimeError('Transformer source-map notices differ; regenerate and review them')
            print('PASS: Transformer source-map notices match audit build')
        else:
            OUTPUT.write_text(content, encoding='utf-8', newline='\n')
            print(f'Wrote {OUTPUT.relative_to(ROOT)}')
    except (OSError, RuntimeError, KeyError, ValueError) as exc:
        print(f'Could not generate Transformer source-map notices: {exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
